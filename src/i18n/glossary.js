// Nombre de vitesses : « 11v » → « 11s » (en), « 11-fach » (de), « 11v » (es, it).
const SPEEDS = { en: '$1s', de: '$1-fach', es: '$1v', it: '$1v' };
const CODES = ['en', 'de', 'es', 'it'];

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

export const GLOSSARY = Object.fromEntries(CODES.map((code, k) => {
  const phrases = ROWS
    .map((row) => [row[0], row[k + 1]])
    .sort((a, b) => b[0].length - a[0].length)
    .map(([fr, target]) => [
      // Limites de mot qui tiennent compte des lettres accentuées.
      new RegExp(`(?<![\\p{L}\\d-])${escapeRe(fr)}(?![\\p{L}-])`, 'giu'),
      (m) => (m[0] === m[0].toUpperCase() && m[0] !== m[0].toLowerCase() ? cap(target) : target),
    ]);
  return [code, { phrases, speeds: SPEEDS[code] }];
}));
